//go:build arm64

#include "textflag.h"

// The Go assembler has no SXTL/SCVTF vector mnemonics, so the int8
// widening pipeline is WORD-encoded. Fixed register choices keep the
// encodings literal:
//   SXTL   V26.8H, V25.8B    = 0x0F08A400 | 25<<5 | 26  = 0x0F08A73A
//   SXTL2  V27.8H, V25.16B   = 0x4F08A400 | 25<<5 | 27  = 0x4F08A73B
//   SXTL   V16.4S, V26.4H    = 0x0F10A400 | 26<<5 | 16  = 0x0F10A750
//   SXTL2  V17.4S, V26.8H    = 0x4F10A400 | 26<<5 | 17  = 0x4F10A751
//   SXTL   V18.4S, V27.4H    = 0x0F10A400 | 27<<5 | 18  = 0x0F10A772
//   SXTL2  V19.4S, V27.8H    = 0x4F10A400 | 27<<5 | 19  = 0x4F10A773
//   SCVTF  Vd.4S, Vd.4S      = 0x4E21D800 | d<<5 | d:
//     V16: 0x4E21DA10  V17: 0x4E21DA31  V18: 0x4E21DA52  V19: 0x4E21DA73
// Each is validated by the qemu-run kernel sweep against the float64
// reference over the dequantized weights.

// func gemm4x16i8(dst *float32, n int, pa *float32, pb *int8, k int, scales *float32)
TEXT ·gemm4x16i8(SB), NOSPLIT, $0-48
	MOVD dst+0(FP), R0
	MOVD n+8(FP), R1
	MOVD pa+16(FP), R2
	MOVD pb+24(FP), R3
	MOVD k+32(FP), R4
	MOVD scales+40(FP), R5
	LSL  $2, R1, R1 // row stride in bytes

	VEOR V0.B16, V0.B16, V0.B16
	VEOR V1.B16, V1.B16, V1.B16
	VEOR V2.B16, V2.B16, V2.B16
	VEOR V3.B16, V3.B16, V3.B16
	VEOR V4.B16, V4.B16, V4.B16
	VEOR V5.B16, V5.B16, V5.B16
	VEOR V6.B16, V6.B16, V6.B16
	VEOR V7.B16, V7.B16, V7.B16
	VEOR V8.B16, V8.B16, V8.B16
	VEOR V9.B16, V9.B16, V9.B16
	VEOR V10.B16, V10.B16, V10.B16
	VEOR V11.B16, V11.B16, V11.B16
	VEOR V12.B16, V12.B16, V12.B16
	VEOR V13.B16, V13.B16, V13.B16
	VEOR V14.B16, V14.B16, V14.B16
	VEOR V15.B16, V15.B16, V15.B16

loop:
	VLD1.P 16(R3), [V25.B16] // 16 int8 B values
	WORD   $0x0F08A73A       // SXTL  V26.8H, V25.8B
	WORD   $0x4F08A73B       // SXTL2 V27.8H, V25.16B
	WORD   $0x0F10A750       // SXTL  V16.4S, V26.4H
	WORD   $0x4F10A751       // SXTL2 V17.4S, V26.8H
	WORD   $0x0F10A772       // SXTL  V18.4S, V27.4H
	WORD   $0x4F10A773       // SXTL2 V19.4S, V27.8H
	WORD   $0x4E21DA10       // SCVTF V16.4S, V16.4S
	WORD   $0x4E21DA31       // SCVTF V17.4S, V17.4S
	WORD   $0x4E21DA52       // SCVTF V18.4S, V18.4S
	WORD   $0x4E21DA73       // SCVTF V19.4S, V19.4S
	VLD1.P 16(R2), [V20.S4]
	VDUP   V20.S[0], V21.S4
	VDUP   V20.S[1], V22.S4
	VDUP   V20.S[2], V23.S4
	VDUP   V20.S[3], V24.S4
	VFMLA  V16.S4, V21.S4, V0.S4
	VFMLA  V17.S4, V21.S4, V1.S4
	VFMLA  V18.S4, V21.S4, V2.S4
	VFMLA  V19.S4, V21.S4, V3.S4
	VFMLA  V16.S4, V22.S4, V4.S4
	VFMLA  V17.S4, V22.S4, V5.S4
	VFMLA  V18.S4, V22.S4, V6.S4
	VFMLA  V19.S4, V22.S4, V7.S4
	VFMLA  V16.S4, V23.S4, V8.S4
	VFMLA  V17.S4, V23.S4, V9.S4
	VFMLA  V18.S4, V23.S4, V10.S4
	VFMLA  V19.S4, V23.S4, V11.S4
	VFMLA  V16.S4, V24.S4, V12.S4
	VFMLA  V17.S4, V24.S4, V13.S4
	VFMLA  V18.S4, V24.S4, V14.S4
	VFMLA  V19.S4, V24.S4, V15.S4
	SUBS   $1, R4, R4
	BNE    loop

	// Dequantize: acc *= scale per column. No vector FMUL mnemonic either,
	// so multiply via FMLA into a zeroed temp, then move back.
	VLD1 (R5), [V28.S4, V29.S4, V30.S4, V31.S4]

	VEOR  V26.B16, V26.B16, V26.B16
	VFMLA V28.S4, V0.S4, V26.S4
	VMOV  V26.B16, V0.B16
	VEOR  V26.B16, V26.B16, V26.B16
	VFMLA V29.S4, V1.S4, V26.S4
	VMOV  V26.B16, V1.B16
	VEOR  V26.B16, V26.B16, V26.B16
	VFMLA V30.S4, V2.S4, V26.S4
	VMOV  V26.B16, V2.B16
	VEOR  V26.B16, V26.B16, V26.B16
	VFMLA V31.S4, V3.S4, V26.S4
	VMOV  V26.B16, V3.B16
	VEOR  V26.B16, V26.B16, V26.B16
	VFMLA V28.S4, V4.S4, V26.S4
	VMOV  V26.B16, V4.B16
	VEOR  V26.B16, V26.B16, V26.B16
	VFMLA V29.S4, V5.S4, V26.S4
	VMOV  V26.B16, V5.B16
	VEOR  V26.B16, V26.B16, V26.B16
	VFMLA V30.S4, V6.S4, V26.S4
	VMOV  V26.B16, V6.B16
	VEOR  V26.B16, V26.B16, V26.B16
	VFMLA V31.S4, V7.S4, V26.S4
	VMOV  V26.B16, V7.B16
	VEOR  V26.B16, V26.B16, V26.B16
	VFMLA V28.S4, V8.S4, V26.S4
	VMOV  V26.B16, V8.B16
	VEOR  V26.B16, V26.B16, V26.B16
	VFMLA V29.S4, V9.S4, V26.S4
	VMOV  V26.B16, V9.B16
	VEOR  V26.B16, V26.B16, V26.B16
	VFMLA V30.S4, V10.S4, V26.S4
	VMOV  V26.B16, V10.B16
	VEOR  V26.B16, V26.B16, V26.B16
	VFMLA V31.S4, V11.S4, V26.S4
	VMOV  V26.B16, V11.B16
	VEOR  V26.B16, V26.B16, V26.B16
	VFMLA V28.S4, V12.S4, V26.S4
	VMOV  V26.B16, V12.B16
	VEOR  V26.B16, V26.B16, V26.B16
	VFMLA V29.S4, V13.S4, V26.S4
	VMOV  V26.B16, V13.B16
	VEOR  V26.B16, V26.B16, V26.B16
	VFMLA V30.S4, V14.S4, V26.S4
	VMOV  V26.B16, V14.B16
	VEOR  V26.B16, V26.B16, V26.B16
	VFMLA V31.S4, V15.S4, V26.S4
	VMOV  V26.B16, V15.B16

	VST1 [V0.S4, V1.S4, V2.S4, V3.S4], (R0)
	ADD  R1, R0, R0
	VST1 [V4.S4, V5.S4, V6.S4, V7.S4], (R0)
	ADD  R1, R0, R0
	VST1 [V8.S4, V9.S4, V10.S4, V11.S4], (R0)
	ADD  R1, R0, R0
	VST1 [V12.S4, V13.S4, V14.S4, V15.S4], (R0)
	RET
